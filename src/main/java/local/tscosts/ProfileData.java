package local.tscosts;

import com.google.gson.Gson;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.security.MessageDigest;
import java.util.List;

public final class ProfileData {
    public int schemaVersion;
    public String measuredAt;
    public String projectRoot;
    public String interpretation;
    public int unmappedEvents;
    public List<FileCost> files;
    public Summary summary;

    public static final class Summary {
        public Double wallMs, prepareMs, compilerWallMs, cpuMs, cpuUserMs, cpuSystemMs;
        public Double peakRssBytes, heapUsedAtExitBytes, tsMemoryBytes;
        public Double checkMs, parseMs, bindMs, programMs, dumpMs, mappedMs;
        public int uniqueEvents, exitCode, projects;
        public String framework, resourceScope;
    }

    public static final class FileCost {
        public String path;
        public String sha256;
        public double fileMs;
        public double mappedMs;
        public List<Hint> hints;
    }

    public static final class Hint {
        public int start;
        public int end;
        public int line;
        public double ms;
        public String kind;
        public String event;
        public String mapping;
        public String detail;
        public String snippet;
        public String eventKey;
        public String title, subject, explanation, sourceSnippet, generatedSnippet, evidence, limitation, children;
        public double childMs, unattributedMs;

        public String label() { return title == null ? kind : title; }
    }

    public static ProfileData read(Path path) throws IOException {
        if (Files.size(path) > 128L * 1024 * 1024) throw new IOException("Profile exceeds 128 MiB");
        ProfileData data;
        try {
            data = new Gson().fromJson(Files.readString(path), ProfileData.class);
        } catch (RuntimeException exception) {
            throw new IOException("Invalid TS Costs profile", exception);
        }
        if (data == null || (data.schemaVersion != 1 && data.schemaVersion != 2) || data.files == null
            || data.projectRoot == null || !Path.of(data.projectRoot).isAbsolute() || data.files.size() > 100_000) {
            throw new IOException("Unsupported profile; select latest-profile.json generated by TS Costs");
        }
        if (data.summary != null) {
            for (java.lang.reflect.Field field : Summary.class.getFields()) {
                if (field.getType() != Double.class) continue;
                try {
                    Double value = (Double) field.get(data.summary);
                    if (value != null && (!Double.isFinite(value) || value < 0)) throw new IOException("Invalid summary metric");
                } catch (IllegalAccessException exception) { throw new IOException(exception); }
            }
        }
        for (FileCost file : data.files) {
            if (file == null || file.path == null || file.path.contains("\\") || Path.of(file.path).isAbsolute()
                || Path.of(file.path).normalize().startsWith("..")
                || file.sha256 == null || !file.sha256.matches("[a-f0-9]{64}")
                || !Double.isFinite(file.fileMs) || file.fileMs < 0 || file.hints == null || file.hints.size() > 100_000) {
                throw new IOException("Invalid file entry in TS Costs profile");
            }
            for (Hint hint : file.hints) {
                if (hint == null || hint.start < 0 || hint.end <= hint.start || !Double.isFinite(hint.ms) || hint.ms < 0
                    || hint.kind == null || hint.event == null) throw new IOException("Invalid hint range");
            }
        }
        return data;
    }

    public static String fingerprint(String text) {
        try {
            String normalized = text.replace("\r\n", "\n");
            if (normalized.startsWith("\uFEFF")) normalized = normalized.substring(1);
            return java.util.HexFormat.of().formatHex(MessageDigest.getInstance("SHA-256")
                .digest(normalized.getBytes(StandardCharsets.UTF_8)));
        } catch (java.security.NoSuchAlgorithmException exception) {
            throw new IllegalStateException(exception);
        }
    }
}
